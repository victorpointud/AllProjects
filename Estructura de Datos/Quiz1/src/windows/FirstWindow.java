     public DoubleCircularList OrderList(DoubleCircularList inList){
         
        DoubleCircularList outList = new DoubleCircularList();
        NodeRadioStation pointer = inList.getHead();
        
        for (int i = 0; i < inList.getTotal(); i++) {
            
            
            
            if(outList.getEmpty()){
                
                outList.insert(pointer, 0);
            }
            else{
                
                NodeRadioStation pointer2 = outList.getHead();
                float f = Float.parseFloat(pointer.getNumber());
                
                for (int j = 0; j < outList.getTotal(); j++){
                    
                    if(f > Float.parseFloat(pointer2.getNumber())){
                        outList.insert(pointer, outList.getTotal() + 1);
                    }
                    else if (f < Float.parseFloat(pointer2.getNumber())){
                        outList.insert(pointer, j);
                    }
                    else{
                        pointer2 = pointer2.getNext();
                    }
                }
                
            }
         pointer = pointer.getNext();
        }
        return outList;
     }
     
