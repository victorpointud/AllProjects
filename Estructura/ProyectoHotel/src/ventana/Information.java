    /*
    *  Muestra la lista de huéspedes dada la habitación. Para ello busca por el número
    *  de habitación en el ABB con el histórico de las habitaciones
    */
    
    private void RoomHistoryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RoomHistoryActionPerformed
        String numHab  = RoomId.getText();
        // Se busca la habitación en el ABB de las habitaciones y se obtiene su historico
        String roomHistory = history.getRoomHistory(numHab);
        InfoText.setText(roomHistory);
    }//GEN-LAST:event_RoomHistoryActionPerformed

