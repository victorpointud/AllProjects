    /*
    *  Muestra la reservación dado la cédula. Para ello busca por el número
    *  de cédula en el ABB con las reservaciones hechas por los clientes.
    */
    
    private void ReservationActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ReservationActionPerformed
        String ci  = ClientId.getText();
        // Se busca la cedula en el ABB de reservaciones y se obtiene sus datos
        String reservationData = reservations.getReservationData(ci);
        InfoText.setText(reservationData);
    }//GEN-LAST:event_ReservationActionPerformed
    
